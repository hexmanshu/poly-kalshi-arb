/// Strategy manager - evaluates all strategies against market data
pub struct StrategyManager {
    strategies: Vec<StrategyConfig>,
}

impl StrategyManager {
    pub fn new(strategies: Vec<StrategyConfig>) -> Self {
        Self { strategies }
    }

    pub fn with_defaults() -> Self {
        Self::new(default_strategies())
    }

    /// Evaluate all enabled strategies against a market snapshot
    pub fn evaluate_all(&self, snapshot: &MarketSnapshot) -> Vec<StrategySignal> {
        self.strategies
            .iter()
            .filter(|s| s.enabled)
            .filter_map(|s| s.evaluate(snapshot))
            .collect()
    }

    /// Get strategy by ID
    pub fn get_strategy(&self, id: &str) -> Option<&StrategyConfig> {
        self.strategies.iter().find(|s| s.id == id)
    }

    /// Get all strategies
    pub fn strategies(&self) -> &[StrategyConfig] {
        &self.strategies
    }

    /// Enable/disable a strategy
    pub fn set_enabled(&mut self, id: &str, enabled: bool) -> bool {
        if let Some(s) = self.strategies.iter_mut().find(|s| s.id == id) {
            s.enabled = enabled;
            true
        } else {
            false
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn make_snapshot(k_yes: u16, k_no: u16, p_yes: u16, p_no: u16) -> MarketSnapshot {
        MarketSnapshot {
            market_id: 0,
            kalshi_yes: k_yes,
            kalshi_no: k_no,
            kalshi_yes_size: 1000,
            kalshi_no_size: 1000,
            poly_yes: p_yes,
            poly_no: p_no,
            poly_yes_size: 1000,
            poly_no_size: 1000,
            timestamp_ns: 0,
        }
    }

    #[test]
    fn test_arb_costs() {
        let snapshot = make_snapshot(50, 50, 40, 55);
        let costs = snapshot.arb_costs();

        // Poly YES (40) + Kalshi NO (50) + fee(50)=2 = 92
        assert_eq!(costs.poly_yes_kalshi_no, 92);

        // Kalshi YES (50) + fee(50)=2 + Poly NO (55) = 107
        assert_eq!(costs.kalshi_yes_poly_no, 107);

        // Poly only: 40 + 55 = 95
        assert_eq!(costs.poly_only, 95);

        // Kalshi only: 50 + 2 + 50 + 2 = 104
        assert_eq!(costs.kalshi_only, 104);
    }

    #[test]
    fn test_conservative_strategy() {
        let strategies = default_strategies();
        let conservative = strategies.iter().find(|s| s.id == "conservative").unwrap();

        // Clear arb: cost = 92, profit = 8
        let snapshot = make_snapshot(55, 50, 40, 60);
        let signal = conservative.evaluate(&snapshot);
        assert!(signal.is_some());
        let sig = signal.unwrap();
        assert_eq!(sig.profit_cents, 8);
    }

    #[test]
    fn test_liquidity_filter() {
        let strategies = default_strategies();
        let liquid = strategies.iter().find(|s| s.id == "liquid_only").unwrap();

        // Good arb but low liquidity
        let mut snapshot = make_snapshot(55, 50, 40, 60);
        snapshot.poly_yes_size = 100;  // Only $1 available

        let signal = liquid.evaluate(&snapshot);
        assert!(signal.is_none(), "Should reject low liquidity");

        // Same arb with good liquidity
        snapshot.poly_yes_size = 1000;
        let signal = liquid.evaluate(&snapshot);
        assert!(signal.is_some());
    }

    #[test]
    fn test_strategy_manager() {
        let manager = StrategyManager::with_defaults();

        let snapshot = make_snapshot(55, 50, 40, 60);
        let signals = manager.evaluate_all(&snapshot);

        // Multiple strategies should trigger on a clear arb
        assert!(!signals.is_empty());
    }
}
