// src/strategy.rs
// Strategy definitions for backtesting arbitrage detection

use crate::types::{ArbType, PriceCents, SizeCents, kalshi_fee_cents};
use serde::{Deserialize, Serialize};

/// Market snapshot for strategy evaluation
#[derive(Debug, Clone, Copy)]
pub struct MarketSnapshot {
    pub market_id: u16,
    pub kalshi_yes: PriceCents,
    pub kalshi_no: PriceCents,
    pub kalshi_yes_size: SizeCents,
    pub kalshi_no_size: SizeCents,
    pub poly_yes: PriceCents,
    pub poly_no: PriceCents,
    pub poly_yes_size: SizeCents,
    pub poly_no_size: SizeCents,
    pub timestamp_ns: u64,
}

impl MarketSnapshot {
    /// Check if all prices are available
    pub fn has_all_prices(&self) -> bool {
        self.kalshi_yes > 0 && self.kalshi_no > 0 &&
        self.poly_yes > 0 && self.poly_no > 0
    }

    /// Calculate cost for each arb type (including fees)
    pub fn arb_costs(&self) -> ArbCosts {
        let k_yes_fee = kalshi_fee_cents(self.kalshi_yes);
        let k_no_fee = kalshi_fee_cents(self.kalshi_no);

        ArbCosts {
            poly_yes_kalshi_no: self.poly_yes + self.kalshi_no + k_no_fee,
            kalshi_yes_poly_no: self.kalshi_yes + k_yes_fee + self.poly_no,
            poly_only: self.poly_yes + self.poly_no,
            kalshi_only: self.kalshi_yes + k_yes_fee + self.kalshi_no + k_no_fee,
        }
    }

    /// Get minimum available size for an arb type
    pub fn min_size_for_arb(&self, arb_type: ArbType) -> SizeCents {
        match arb_type {
            ArbType::PolyYesKalshiNo => self.poly_yes_size.min(self.kalshi_no_size),
            ArbType::KalshiYesPolyNo => self.kalshi_yes_size.min(self.poly_no_size),
            ArbType::PolyOnly => self.poly_yes_size.min(self.poly_no_size),
            ArbType::KalshiOnly => self.kalshi_yes_size.min(self.kalshi_no_size),
        }
    }
}

/// Costs for each arbitrage type
#[derive(Debug, Clone, Copy)]
pub struct ArbCosts {
    pub poly_yes_kalshi_no: u16,
    pub kalshi_yes_poly_no: u16,
    pub poly_only: u16,
    pub kalshi_only: u16,
}

impl ArbCosts {
    /// Get cost for a specific arb type
    pub fn for_type(&self, arb_type: ArbType) -> u16 {
        match arb_type {
            ArbType::PolyYesKalshiNo => self.poly_yes_kalshi_no,
            ArbType::KalshiYesPolyNo => self.kalshi_yes_poly_no,
            ArbType::PolyOnly => self.poly_only,
            ArbType::KalshiOnly => self.kalshi_only,
        }
    }

    /// Get best (lowest) cost and its type
    pub fn best(&self) -> (u16, ArbType) {
        let mut best_cost = self.poly_yes_kalshi_no;
        let mut best_type = ArbType::PolyYesKalshiNo;

        if self.kalshi_yes_poly_no < best_cost {
            best_cost = self.kalshi_yes_poly_no;
            best_type = ArbType::KalshiYesPolyNo;
        }
        if self.poly_only < best_cost {
            best_cost = self.poly_only;
            best_type = ArbType::PolyOnly;
        }
        if self.kalshi_only < best_cost {
            best_cost = self.kalshi_only;
            best_type = ArbType::KalshiOnly;
        }

        (best_cost, best_type)
    }
}

/// Signal generated by a strategy
#[derive(Debug, Clone)]
pub struct StrategySignal {
    pub strategy_id: String,
    pub market_id: u16,
    pub arb_type: ArbType,
    pub cost_cents: u16,
    pub profit_cents: i16,
    pub yes_price: PriceCents,
    pub no_price: PriceCents,
    pub yes_size: SizeCents,
    pub no_size: SizeCents,
    pub confidence: f64,  // 0.0 - 1.0, strategy-specific confidence
    pub timestamp_ns: u64,
}

/// Strategy configuration - serializable for persistence
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StrategyConfig {
    pub id: String,
    pub name: String,
    pub description: String,
    pub params: StrategyParams,
    pub enabled: bool,
}

/// Strategy parameters
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StrategyParams {
    /// Maximum cost threshold in cents (100 = breakeven)
    pub threshold_cents: u16,

    /// Minimum profit in cents to trigger
    pub min_profit_cents: i16,

    /// Minimum liquidity (size) in cents on each side
    pub min_size_cents: u16,

    /// Only trigger on cross-platform arbs (not same-platform)
    pub cross_platform_only: bool,

    /// Only trigger on same-platform arbs
    pub same_platform_only: bool,

    /// Minimum price for YES side (filter extreme prices)
    pub min_yes_price: PriceCents,

    /// Maximum price for YES side
    pub max_yes_price: PriceCents,

    /// Minimum price for NO side
    pub min_no_price: PriceCents,

    /// Maximum price for NO side
    pub max_no_price: PriceCents,

    /// Prefer Polymarket leg (they have no fees)
    pub prefer_poly_leg: bool,

    /// Maximum Kalshi fee to accept (cents)
    pub max_kalshi_fee_cents: u16,
}

impl Default for StrategyParams {
    fn default() -> Self {
        Self {
            threshold_cents: 100,  // Breakeven
            min_profit_cents: 0,
            min_size_cents: 0,
            cross_platform_only: false,
            same_platform_only: false,
            min_yes_price: 1,
            max_yes_price: 99,
            min_no_price: 1,
            max_no_price: 99,
            prefer_poly_leg: false,
            max_kalshi_fee_cents: 10,
        }
    }
}

impl StrategyConfig {
    /// Evaluate this strategy against a market snapshot
    pub fn evaluate(&self, snapshot: &MarketSnapshot) -> Option<StrategySignal> {
        if !self.enabled || !snapshot.has_all_prices() {
            return None;
        }

        let costs = snapshot.arb_costs();
        let params = &self.params;

        // Find all arbs that pass the threshold
        let arb_types = [
            (ArbType::PolyYesKalshiNo, costs.poly_yes_kalshi_no, snapshot.poly_yes, snapshot.kalshi_no),
            (ArbType::KalshiYesPolyNo, costs.kalshi_yes_poly_no, snapshot.kalshi_yes, snapshot.poly_no),
            (ArbType::PolyOnly, costs.poly_only, snapshot.poly_yes, snapshot.poly_no),
            (ArbType::KalshiOnly, costs.kalshi_only, snapshot.kalshi_yes, snapshot.kalshi_no),
        ];

        let mut best_signal: Option<StrategySignal> = None;

        for (arb_type, cost, yes_price, no_price) in arb_types {
            // Threshold check
            if cost > params.threshold_cents {
                continue;
            }

            let profit = 100i16 - cost as i16;

            // Minimum profit check
            if profit < params.min_profit_cents {
                continue;
            }

            // Platform preference checks
            let is_cross = matches!(arb_type, ArbType::PolyYesKalshiNo | ArbType::KalshiYesPolyNo);
            if params.cross_platform_only && !is_cross {
                continue;
            }
            if params.same_platform_only && is_cross {
                continue;
            }

            // Price range checks
            if yes_price < params.min_yes_price || yes_price > params.max_yes_price {
                continue;
            }
            if no_price < params.min_no_price || no_price > params.max_no_price {
                continue;
            }

            // Liquidity check
            let min_size = snapshot.min_size_for_arb(arb_type);
            if min_size < params.min_size_cents {
                continue;
            }

            // Kalshi fee check
            let kalshi_fee = match arb_type {
                ArbType::PolyYesKalshiNo => kalshi_fee_cents(no_price),
                ArbType::KalshiYesPolyNo => kalshi_fee_cents(yes_price),
                ArbType::PolyOnly => 0,
                ArbType::KalshiOnly => kalshi_fee_cents(yes_price) + kalshi_fee_cents(no_price),
            };
            if kalshi_fee > params.max_kalshi_fee_cents {
                continue;
            }

            // Calculate confidence based on how far below threshold
            let confidence = if params.threshold_cents > 0 {
                ((params.threshold_cents - cost) as f64 / params.threshold_cents as f64).min(1.0)
            } else {
                1.0
            };

            // Prefer poly leg if configured
            let adjusted_confidence = if params.prefer_poly_leg {
                match arb_type {
                    ArbType::PolyYesKalshiNo | ArbType::PolyOnly => confidence * 1.1,
                    _ => confidence * 0.9,
                }
            } else {
                confidence
            };

            let (yes_size, no_size) = match arb_type {
                ArbType::PolyYesKalshiNo => (snapshot.poly_yes_size, snapshot.kalshi_no_size),
                ArbType::KalshiYesPolyNo => (snapshot.kalshi_yes_size, snapshot.poly_no_size),
                ArbType::PolyOnly => (snapshot.poly_yes_size, snapshot.poly_no_size),
                ArbType::KalshiOnly => (snapshot.kalshi_yes_size, snapshot.kalshi_no_size),
            };

            let signal = StrategySignal {
                strategy_id: self.id.clone(),
                market_id: snapshot.market_id,
                arb_type,
                cost_cents: cost,
                profit_cents: profit,
                yes_price,
                no_price,
                yes_size,
                no_size,
                confidence: adjusted_confidence.min(1.0),
                timestamp_ns: snapshot.timestamp_ns,
            };

            // Keep best signal (highest profit, or highest confidence if tied)
            if let Some(ref best) = best_signal {
                if signal.profit_cents > best.profit_cents ||
                   (signal.profit_cents == best.profit_cents && signal.confidence > best.confidence) {
                    best_signal = Some(signal);
                }
            } else {
                best_signal = Some(signal);
            }
        }

        best_signal
    }
}

